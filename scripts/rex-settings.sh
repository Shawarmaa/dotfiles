#!/usr/bin/env bash
# Save or apply the Rex app's appearance settings.
#
#   ./scripts/rex-settings.sh save    write this Mac's settings into the repo
#   ./scripts/rex-settings.sh apply   apply the repo's settings to this Mac
#
# Rex stores theme, font, tab style and sidebar in the com.superlogical.rex
# preferences domain, not in init.lua. Only Workspace.* keys are kept, minus
# per-machine state such as the last focused session and window frames.
set -euo pipefail

REPO_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
FILE="$REPO_DIR/rex/.config/rex/app-settings.sh"
DOMAIN=com.superlogical.rex

case "${1:-}" in
  save)
    defaults export "$DOMAIN" - | /usr/bin/python3 -c '
import plistlib, shlex, sys
prefs = plistlib.loads(sys.stdin.buffer.read())
skip = {"Workspace.lastFocusedSession"}
print("# Generated by scripts/rex-settings.sh save — applied by scripts/rex-settings.sh apply.")
for k in sorted(prefs):
    v = prefs[k]
    if not k.startswith("Workspace.") or k in skip:
        continue
    if isinstance(v, bool):    t, s = "-bool", "true" if v else "false"
    elif isinstance(v, int):   t, s = "-int", str(v)
    elif isinstance(v, float): t, s = "-float", repr(v)
    elif isinstance(v, str):   t, s = "-string", shlex.quote(v)
    else: continue
    print(f"defaults write {sys.argv[1]} {shlex.quote(k)} {t} {s}")
' "$DOMAIN" > "$FILE"
    echo "saved $(grep -c '^defaults' "$FILE") setting(s) to ${FILE#$REPO_DIR/}"
    ;;
  apply)
    [ -f "$FILE" ] || { echo "no $FILE — run save first"; exit 1; }
    # Rex rewrites its preferences on quit, so settings applied while it runs
    # can be lost.
    pgrep -qx Rex && echo "note: Rex is running — quit and reopen it to pick these up"
    # shellcheck source=/dev/null
    . "$FILE"
    echo "applied $(grep -c '^defaults' "$FILE") setting(s)"
    ;;
  *)
    sed -n '2,5p' "$0"; exit 2 ;;
esac
